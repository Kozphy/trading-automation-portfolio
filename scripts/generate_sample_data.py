"""Regenerate bundled SYNTHETIC sample data (deterministic)."""

from pathlib import Path

import numpy as np
import pandas as pd
from tradebot.data import generate_synthetic_ohlcv

ROOT = Path(__file__).resolve().parents[1] / "data"

if __name__ == "__main__":
    ROOT.mkdir(exist_ok=True)
    df = generate_synthetic_ohlcv(n=3000, seed=42)
    out = ROOT / "synthetic_btcusdt_1h.csv"
    with out.open("w") as f:
        f.write("# SYNTHETIC DATA - generated by scripts/generate_sample_data.py (seed=42). "
                "NOT real market prices.\n")
        df.to_csv(f, index=False, float_format="%.4f")
    rng = np.random.default_rng(7)
    n = 60
    entries = pd.date_range("2024-03-01", periods=n, freq="7h", tz="UTC")
    journal = pd.DataFrame({
        "entry_time": entries,
        "exit_time": entries + pd.to_timedelta(rng.integers(1, 12, n), unit="h"),
        "symbol": rng.choice(["BTC/USDT", "ETH/USDT", "XAUUSD"], n),
        "side": rng.choice(["long", "short"], n),
        "pnl": rng.normal(5, 60, n).round(2),
    })
    jout = ROOT / "synthetic_trade_journal.csv"
    with jout.open("w") as f:
        f.write("# SYNTHETIC trade journal (seed=7). Not real trades.\n")
        journal.to_csv(f, index=False)
    print(f"wrote {out} and {jout}")
